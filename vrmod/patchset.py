LAYERS_KEY = r"Software\Microsoft\Windows NT\CurrentVersion\AppCompatFlags\Layers"
LAUNCHER = "Viper Racing.exe"
RACE_EXE = "race.exe"   # v1.0's engine -- see _dpi_targets()


def _dpi_targets(data_dir: str | Path) -> list[Path]:
    """The executables a DPI compatibility layer may need to sit on.

    Two candidates, because which one Windows honours is genuinely ambiguous:

      * `race.bin` -- the REAL game process. `Viper Racing.exe` only
        `CreateProcess`-es it and imports no graphics DLLs, so race.bin is what
        owns the window and renders (it imports DDRAW/DSOUND). Windows tracks it
        as a program in its own right -- the Program Compatibility Assistant
        auto-adds a `DWM8And16BitMitigation` layer to the race.bin path -- so a
        layer keyed to race.bin is honoured despite the `.bin` extension.
      * `Viper Racing.exe` -- the launcher. Empirically, setting HIGHDPIAWARE
        here ALSO fixes rendering, most likely because a compatibility shim set
        on a parent propagates to the child it spawns.

    So the flag is set on both, and considered present if either has it. An
    earlier version targeted only the launcher, and named it "the process that
    owns the window", which is wrong -- race.bin is.

    On a v1.0 install neither of those is the game: `race.exe` is the engine, and
    Data's contents ARE the install directory, so there is no launcher in the
    parent. Flagging only race.bin there sets the layer on a file the build never
    loads and the scaling is not fixed, with nothing to say the flag went
    nowhere. race.exe is therefore included, and listed first.

    The launcher is looked for in BOTH places: an installed 1.1 tree keeps it in
    the parent beside Data\\, but on the retail disc it ships INSIDE Data\\ and
    only moves up when SETUP runs. Checking one location means missing it
    whenever the folder being examined is the disc itself.
    """
    d = Path(data_dir)
    return [d / RACE_EXE, d / RACE_BIN, d.parent / LAUNCHER, d / LAUNCHER]


def scaling_active() -> bool | None:
    """Is the desktop being scaled for DPI-unaware processes? None if unknowable."""
    try:
        import ctypes
        user32 = ctypes.windll.user32
        virt_w = user32.GetSystemMetrics(0)                 # what an unaware app sees
        real_w = ctypes.windll.gdi32.GetDeviceCaps(
            user32.GetDC(0), 118)                           # DESKTOPHORZRES: physical
        return bool(real_w and virt_w and real_w != virt_w)
    except Exception:
        return None


def dpi_aware(data_dir: str | Path) -> bool:
    """Is the HIGHDPIAWARE layer WRITTEN for any of this install's executables?

    ⚠️ This reports what is in the registry, NOT that the layer is in effect.
    They are not the same thing, and the gap is reproducible: writing
    `~ HIGHDPIAWARE` here can leave the game still rendering DPI-unaware, while
    setting the identical value through Properties -> Compatibility -> Change
    high DPI settings fixes it immediately. Confirmed by comparing the two --
    the stored value was byte-for-byte the same either way, so the difference is
    not what is written but that the dialog also refreshes the AppCompat shim
    cache, which a bare registry write does not.

    So treat a True here as "the setting is recorded", and the Compatibility
    dialog as the authority on whether it applies.
    """
    try:
        import winreg
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, LAYERS_KEY) as k:
            for exe in _dpi_targets(data_dir):
                try:
                    if "HIGHDPIAWARE" in winreg.QueryValueEx(k, str(exe))[0]:
                        return True
                except FileNotFoundError:
                    continue
    except Exception:
        pass
    return False


def set_dpi_aware(data_dir: str | Path, enable: bool = True) -> str:
    """Add or remove the launcher's HIGHDPIAWARE layer for the current user.

    This writes to HKEY_CURRENT_USER only and is exactly what the Compatibility
    tab writes when you tick "Override high DPI scaling behavior -- Scaling
    performed by: Application". Callers should make this an explicit choice
    rather than part of a default install.

    ⚠️ WRITING IT IS NOT THE SAME AS IT TAKING EFFECT. Observed repeatedly: the
    value lands correctly and the game still renders DPI-unaware, then setting
    the SAME value through the dialog fixes it at once. The stored strings were
    compared and are identical, so the dialog is doing something besides writing
    -- refreshing the shim cache -- that this cannot reproduce. Always tell the
    user the dialog is the fallback; never report this as a completed fix.
    """
    import winreg
    targets = [e for e in _dpi_targets(data_dir) if e.is_file()]
    if not targets:
        raise PatchSetError(
            f"no {RACE_EXE}, {RACE_BIN} or {LAUNCHER} to flag in {data_dir}")
    key = winreg.CreateKey(winreg.HKEY_CURRENT_USER, LAYERS_KEY)
    results = []
    try:
        for exe in targets:
            try:
                current = winreg.QueryValueEx(key, str(exe))[0]
            except FileNotFoundError:
                current = ""
            # keep any existing layers (e.g. the PCA's DWM8And16BitMitigation);
            # only add or remove HIGHDPIAWARE.
            layers = [t for t in current.split() if t not in ("HIGHDPIAWARE", "~")]
            if enable:
                layers.insert(0, "HIGHDPIAWARE")
            if layers:
                winreg.SetValueEx(key, str(exe), 0, winreg.REG_SZ, " ".join(["~"] + layers))
                results.append(f"{exe.name}: {' '.join(['~'] + layers)}")
            else:
                try:
                    winreg.DeleteValue(key, str(exe))
                    results.append(f"{exe.name}: compatibility layers cleared")
                except FileNotFoundError:
                    results.append(f"{exe.name}: nothing to clear")
    finally:
        winreg.CloseKey(key)
    return "; ".join(results)
